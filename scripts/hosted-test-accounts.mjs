// Creates the SYNTHETIC test accounts the live suites need in the hosted DEVELOPMENT project and writes
// .env.live.dev.local (git-ignored). Requires `npx supabase login`. The project's secret key is fetched
// through the CLI and kept in memory only; nothing secret is printed.
//   node scripts/hosted-test-accounts.mjs <dev-project-ref>
import { execFileSync } from 'node:child_process';
import { randomBytes } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { createClient } from '@supabase/supabase-js';

const ref = process.argv[2];
if (!/^[a-z0-9]{20}$/.test(ref ?? '')) throw new Error('usage: node scripts/hosted-test-accounts.mjs <dev-project-ref>');
const keys = JSON.parse(execFileSync('npx', ['supabase', 'projects', 'api-keys', '--project-ref', ref, '--reveal', '-o', 'json'],
  { encoding: 'utf8', shell: true, stdio: ['ignore', 'pipe', 'ignore'] }));
const pick = (pred) => keys.find(pred)?.api_key;
const secret = pick((k) => k.type === 'secret') ?? pick((k) => k.name === 'service_role');
const publishable = pick((k) => k.type === 'publishable') ?? pick((k) => k.name === 'anon');
if (!secret || !publishable) throw new Error('could not read the project keys (is `supabase login` done?)');
const url = `https://${ref}.supabase.co`;

const pw = () => randomBytes(18).toString('base64url') + 'a1';
const run = Date.now().toString(36);
const accounts = {
  OWNER: { email: 'fm-test-owner@example.com', allowed: true },
  OWNER2: { email: 'fm-test-owner2@example.com', allowed: true },
  OUTSIDER: { email: 'fm-test-outsider@example.com', allowed: false },
};
for (let i = 1; i <= 4; i++) accounts[`RESTORE_${i}`] = { email: `fm-test-restore-${run}-${i}@example.com`, allowed: true };

const admin = createClient(url, secret, { auth: { persistSession: false, autoRefreshToken: false } });
const { data: list, error: listErr } = await admin.auth.admin.listUsers({ perPage: 1000 });
if (listErr) throw listErr;
for (const a of Object.values(accounts)) {
  a.password = pw();
  const existing = list.users.find((u) => u.email === a.email);
  const { error } = existing
    ? await admin.auth.admin.updateUserById(existing.id, { password: a.password })
    : await admin.auth.admin.createUser({ email: a.email, password: a.password, email_confirm: true, user_metadata: { synthetic_test_account: true } });
  if (error) throw error;
  const r = await admin.rpc('admin_set_allowed', { p_email: a.email, p_allowed: a.allowed });
  if (r.error) throw new Error(`allow-list: ${r.error.message}`);
}

const lines = ['# Generated by scripts/hosted-test-accounts.mjs — hosted DEVELOPMENT project, synthetic accounts. Git-ignored.',
  'FM_LIVE_TARGET=dev', `FM_LIVE_DEV_PROJECT_REF=${ref}`, `FM_LIVE_SUPABASE_URL=${url}`, `FM_LIVE_PUBLISHABLE_KEY=${publishable}`];
for (const [k, a] of Object.entries(accounts)) lines.push(`FM_LIVE_${k}_EMAIL=${a.email}`, `FM_LIVE_${k}_PASSWORD=${a.password}`);
writeFileSync('.env.live.dev.local', lines.join('\n') + '\n');
console.log(`✓ ${Object.keys(accounts).length} synthetic accounts ready in ${ref} (3 owners incl. 4 restore targets allow-listed, 1 outsider); wrote .env.live.dev.local`);
