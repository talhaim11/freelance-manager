// Prepares the LOCAL Supabase stack (npx supabase start) for the live test suites:
// creates three synthetic accounts, allow-lists two of them, and writes
// .env.live.local (git-ignored). Prints no keys or passwords.
//
// The local stack's secret key is used here only, in memory, against 127.0.0.1.
import { execSync } from 'node:child_process';
import { randomBytes } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { createClient } from '@supabase/supabase-js';
import pg from 'pg';

const status = JSON.parse(execSync('npx supabase status -o json', { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }));
const url = status.API_URL;
const publishable = status.PUBLISHABLE_KEY || status.ANON_KEY;
const admin = status.SERVICE_ROLE_KEY || status.SECRET_KEY;
if (!url || !publishable || !admin || !status.DB_URL) throw new Error('local stack not running (npx supabase start)');
if (!/127\.0\.0\.1|localhost/.test(url)) throw new Error('refusing: not a local stack');

const pw = () => randomBytes(18).toString('base64url') + 'a1';
const accounts = {
  OWNER: { email: 'fm-owner@example.com', password: pw(), allowed: true },
  OWNER2: { email: 'fm-owner2@example.com', password: pw(), allowed: true },
  OUTSIDER: { email: 'fm-outsider@example.com', password: pw(), allowed: false },
};
// Empty allow-listed accounts that the restore tests consume one at a time (a restored account cannot be
// emptied again: issued documents are immutable). Re-running this script adds fresh ones.
const run = Date.now().toString(36);
for (let i = 1; i <= 4; i++) accounts[`RESTORE_${i}`] = { email: `fm-restore-${run}-${i}@example.com`, password: pw(), allowed: true };

const sb = createClient(url, admin, { auth: { persistSession: false, autoRefreshToken: false } });
const { data: list, error: listErr } = await sb.auth.admin.listUsers({ perPage: 1000 });
if (listErr) throw listErr;
for (const a of Object.values(accounts)) {
  const existing = list.users.find((u) => u.email === a.email);
  const { error } = existing
    ? await sb.auth.admin.updateUserById(existing.id, { password: a.password })
    : await sb.auth.admin.createUser({ email: a.email, password: a.password, email_confirm: true });
  if (error) throw error;
}

const db = new pg.Client({ connectionString: status.DB_URL });
await db.connect();
for (const a of Object.values(accounts)) {
  if (a.allowed) await db.query('insert into app.allowed_users(email) values ($1) on conflict do nothing', [a.email]);
  else await db.query('delete from app.allowed_users where email = $1', [a.email]);
}
await db.end();

const lines = ['# Generated by scripts/live-local-setup.mjs for the LOCAL stack only. Git-ignored.', 'FM_LIVE_TARGET=local',
  `FM_LIVE_SUPABASE_URL=${url}`, `FM_LIVE_PUBLISHABLE_KEY=${publishable}`];
for (const [k, a] of Object.entries(accounts)) lines.push(`FM_LIVE_${k}_EMAIL=${a.email}`, `FM_LIVE_${k}_PASSWORD=${a.password}`);
writeFileSync('.env.live.local', lines.join('\n') + '\n');
console.log('✓ local stack ready: 2 allow-listed test accounts + 1 outsider; wrote .env.live.local');
